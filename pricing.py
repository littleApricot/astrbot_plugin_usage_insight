"""Official DeepSeek tariffs, cached locally and resolved at request time."""

from __future__ import annotations

import asyncio
import copy
import json
import re
from datetime import datetime, timezone
from decimal import Decimal
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import urlsplit
from zoneinfo import ZoneInfo

import aiohttp

SOURCE = "https://api-docs.deepseek.com/zh-cn/quick_start/pricing/"
CALENDAR_SOURCE = (
    "https://www.beijing.gov.cn/zhengce/zhengcefagui/202511/t20251104_4258873.html"
)
HOLIDAYS = {
    2026: (
        ("01-01", "01-03"),
        ("02-15", "02-23"),
        ("04-04", "04-06"),
        ("05-01", "05-05"),
        ("06-19", "06-21"),
        ("09-25", "09-27"),
        ("10-01", "10-07"),
    )
}
ALIASES = {
    "deepseek-v4-flash": "deepseek-flash",
    "deepseek-v4-flash-vision-exp": "deepseek-flash",
}


def api_host(config):
    """Retain only a hostname, never credentials or query strings."""
    try:
        return (urlsplit(str(config.get("api_base", ""))).hostname or "").lower()
    except ValueError:
        return ""


class PriceTable(HTMLParser):
    def __init__(self):
        super().__init__()
        self.rows, self.text, self.row, self.cell = [], [], [], None

    def handle_starttag(self, tag, attrs):
        if tag == "tr":
            self.row = []
        if tag in ("td", "th"):
            self.cell = []

    def handle_data(self, data):
        self.text.append(data)
        if self.cell is not None:
            self.cell.append(data)

    def handle_endtag(self, tag):
        if tag in ("td", "th") and self.cell is not None:
            self.row.append("".join(self.cell).strip())
            self.cell = None
        if tag == "tr":
            self.rows.append(self.row)


def parse_official(html):
    table = PriceTable()
    table.feed(html)
    text = re.sub(r"\s+", "", "".join(table.text))
    for required in (
        "北京时间周一至周五（不含中国法定节假日）9:00-12:00、14:00-18:00",
        "包括周末及中国法定节假日全天均为空闲时段",
    ):
        if required not in text:
            raise ValueError("官方峰谷规则已变更，需要更新插件")
    models, prices = None, []
    for row in table.rows:
        if row and row[0] == "模型":
            models = [re.sub(r"\(\d+\)$", "", name) for name in row[1:]]
        if any(cell in ("空闲时段", "高峰时段") for cell in row):
            if models != ["deepseek-flash", "deepseek-v4-pro"]:
                raise ValueError("官方模型表结构已变更")
            expected = "空闲时段" if len(prices) % 2 == 0 else "高峰时段"
            if expected not in row or len(row) < 3:
                raise ValueError("官方价格行结构已变更")
            amounts = []
            for cell in row[-2:]:
                if not re.fullmatch(r"\d+(?:\.\d+)?元", cell):
                    raise ValueError("官方价格格式无效")
                amounts.append(cell[:-1])
            prices.append(amounts)
    if len(prices) != 6:
        raise ValueError("未找到完整的官方价格")
    result = {model: {"peak": {}, "off_peak": {}} for model in models or []}
    for i, field in enumerate(("cached", "input", "output")):
        for j, model in enumerate(models):
            low, high = prices[i * 2][j], prices[i * 2 + 1][j]
            if Decimal(low) * 2 != Decimal(high):
                raise ValueError("官方峰谷倍率已变更")
            result[model]["off_peak"][field] = low
            result[model]["peak"][field] = high
    return {
        "source": SOURCE,
        "observed_at": datetime.now(timezone.utc).isoformat(),
        "currency": "CNY",
        "models": result,
    }


def period_at(timestamp):
    date = datetime.fromtimestamp(timestamp, ZoneInfo("Asia/Shanghai"))
    minutes = date.hour * 60 + date.minute
    if date.weekday() >= 5 or not (540 <= minutes < 720 or 840 <= minutes < 1080):
        return "off_peak"
    if date.year not in HOLIDAYS:
        return None
    day = date.strftime("%m-%d")
    return (
        "off_peak"
        if any(start <= day <= end for start, end in HOLIDAYS[date.year])
        else "peak"
    )


class PricingCatalog:
    def __init__(self, directory):
        self.path = Path(directory) / "deepseek-prices.json"
        self.data = json.loads(
            Path(__file__).with_name("deepseek_prices.json").read_text(encoding="utf-8")
        )
        self.state, self.error, self.hosts = "bundled", "", {}
        self.lock = asyncio.Lock()
        if self.path.exists():
            try:
                cached = json.loads(self.path.read_text(encoding="utf-8"))
                # Accept only the schema generated by the public-page parser.
                if cached["source"] != SOURCE or cached["currency"] != "CNY":
                    raise ValueError("invalid cached source")
                for model in ("deepseek-flash", "deepseek-v4-pro"):
                    for period in ("peak", "off_peak"):
                        for field in ("input", "cached", "output"):
                            value = Decimal(cached["models"][model][period][field])
                            if not value.is_finite() or value < 0:
                                raise ValueError("invalid cached price")
                observed = datetime.fromisoformat(cached["observed_at"])
                if observed >= datetime.fromisoformat(self.data["observed_at"]):
                    self.data, self.state = cached, "cached"
            except (ValueError, KeyError, TypeError):
                self.error = "InvalidCache"

    def bind_providers(self, providers):
        self.hosts = {
            str(p.provider_config.get("id", "")): api_host(p.provider_config)
            for p in providers
        }

    def resolve(self, row):
        host = row.get("api_host", self.hosts.get(row["provider"], ""))
        model = ALIASES.get(row["model"], row["model"])
        if host != "api.deepseek.com" or model not in self.data["models"]:
            return None
        period = period_at(row["ts"])
        if period is None:
            return None
        return {
            **self.data["models"][model][period],
            "currency": "CNY",
            "source": SOURCE,
            "observed_at": self.data["observed_at"],
            "period": period,
            "basis": "official_snapshot",
        }

    def status(self):
        return {
            **copy.deepcopy(self.data),
            "state": self.state,
            "error": self.error,
            "calendar_source": CALENDAR_SOURCE,
            "calendar_years": sorted(HOLIDAYS),
            "providers": sorted(
                k for k, v in self.hosts.items() if v == "api.deepseek.com"
            ),
        }

    async def refresh(self):
        async with self.lock:
            try:
                async with aiohttp.ClientSession(
                    timeout=aiohttp.ClientTimeout(total=20)
                ) as session:
                    async with session.get(SOURCE, allow_redirects=False) as response:
                        response.raise_for_status()
                        body = bytearray()
                        async for chunk in response.content.iter_chunked(65536):
                            body.extend(chunk)
                            if len(body) > 1000000:
                                raise ValueError("price page too large")
                updated = parse_official(body.decode("utf-8"))
                temporary = self.path.with_suffix(".tmp")
                temporary.write_text(
                    json.dumps(updated, ensure_ascii=False), encoding="utf-8"
                )
                temporary.replace(self.path)
                self.data, self.state, self.error = updated, "synced", ""
                return True
            except asyncio.CancelledError:
                raise
            except Exception as exc:
                self.error = type(exc).__name__
                return False

    async def run(self):
        while True:
            await self.refresh()
            await asyncio.sleep(86400)
